const std::uint8_t* GlyphRows(char32_t codepoint) {
    if (codepoint < 0x20 || codepoint > 0x7E) {
        codepoint = U'?';
    }
    return kGlyphs[codepoint - 0x20];
}

bool MeasureText(const std::string& utf8, int scale, int* out_w,
                 int* out_h) {
    if (out_w == nullptr || out_h == nullptr || scale < 1) {
        return false;
    }
    const auto lines = DecodeLines(utf8);
    if (lines.empty() || (lines.size() == 1 && lines.front().empty())) {
        *out_w = 0;
        *out_h = 0;
        return true;
    }
    std::size_t max_cols = 0;
    for (const auto& line : lines) {
        max_cols = std::max(max_cols, line.size());
    }
    // Advance-per-glyph minus the trailing tracking column; leading
    // after the last line is trimmed the same way.
    *out_w = static_cast<int>(max_cols * kGlyphAdvance - 1) * scale;
    *out_h = static_cast<int>(lines.size() * kLineAdvance - 2) * scale;
    return true;
}

void DrawText(video::Frame* frame, const std::string& utf8,
              int origin_x, int origin_y, int scale,
              const std::array<std::uint8_t, 4>& bgra) {
    if (frame == nullptr || !frame->IsValid() ||
        frame->Format() != video::PixelFormat::BGRA8 || scale < 1) {
        return;
    }
    const auto lines = DecodeLines(utf8);
    const int fw = frame->Width();
    const int fh = frame->Height();
    std::uint8_t* px = frame->Data();
    for (std::size_t line_index = 0; line_index < lines.size();
         ++line_index) {
        const int base_y =
            origin_y + static_cast<int>(line_index) * kLineAdvance * scale;
        int pen_x = origin_x;
        for (const char32_t cp : lines[line_index]) {
            const std::uint8_t* rows = GlyphRows(cp);
            for (int gy = 0; gy < kGlyphHeight; ++gy) {
                const std::uint8_t row = rows[gy];
                if (row == 0) {
                    continue;   // blank row — common, skip fast
                }
                for (int gx = 0; gx < kGlyphWidth; ++gx) {
                    if ((row & (0x10u >> gx)) == 0) {
                        continue;
                    }
                    // Fill the scale x scale destination block for
                    // this glyph pixel.
                    const int dx0 = pen_x + gx * scale;
                    const int dy0 = base_y + gy * scale;
                    for (int sy = 0; sy < scale; ++sy) {
                        const int dy = dy0 + sy;
                        if (dy < 0 || dy >= fh) {
                            continue;
                        }
                        for (int sx = 0; sx < scale; ++sx) {
                            const int dx = dx0 + sx;
                            if (dx < 0 || dx >= fw) {
                                continue;
                            }
                            OverPixel(
                                px + (static_cast<std::size_t>(dy) * fw +
                                      dx) * 4u,
                                bgra.data());
                        }
                    }
                }
            }
            pen_x += kGlyphAdvance * scale;
        }
    }
}

