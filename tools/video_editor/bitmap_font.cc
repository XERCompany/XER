// Decodes `utf8` into lines of codepoints split on '\n' (and '\r' —
// CRLF pairs collapse to one break). Malformed sequences yield one
// U+FFFD per bad byte, never a stall or a crash. A trailing '\n'
// produces a final empty line (measures as blank space, draws
// nothing) — matching title-tool behavior.
std::vector<std::vector<char32_t>> DecodeLines(const std::string& utf8) {
    std::vector<std::vector<char32_t>> lines(1);
    const std::size_t n = utf8.size();
    std::size_t i = 0;
    while (i < n) {
        const auto byte = static_cast<std::uint8_t>(utf8[i]);
        if (byte == '\n') {
            lines.emplace_back();
            ++i;
            continue;
        }
        if (byte == '\r') {
            if (i + 1 < n && utf8[i + 1] == '\n') {
                ++i;   // swallow the LF of a CRLF pair
            }
            lines.emplace_back();
            ++i;
            continue;
        }
        char32_t cp;
        std::size_t len;
        if (byte < 0x80) {
            cp = byte;
            len = 1;
        } else if ((byte >> 5) == 0x6 && i + 1 < n &&
                   (static_cast<std::uint8_t>(utf8[i + 1]) & 0xC0) ==
                       0x80) {
            cp = ((byte & 0x1F) << 6) |
                 (static_cast<std::uint8_t>(utf8[i + 1]) & 0x3F);
            len = 2;
        } else if ((byte >> 4) == 0xE && i + 2 < n &&
                   (static_cast<std::uint8_t>(utf8[i + 1]) & 0xC0) ==
                       0x80 &&
                   (static_cast<std::uint8_t>(utf8[i + 2]) & 0xC0) ==
                       0x80) {
            cp = ((byte & 0x0F) << 12) |
                 ((static_cast<std::uint8_t>(utf8[i + 1]) & 0x3F) << 6) |
                 (static_cast<std::uint8_t>(utf8[i + 2]) & 0x3F);
            len = 3;
        } else if ((byte >> 3) == 0x1E && i + 3 < n &&
                   (static_cast<std::uint8_t>(utf8[i + 1]) & 0xC0) ==
                       0x80 &&
                   (static_cast<std::uint8_t>(utf8[i + 2]) & 0xC0) ==
                       0x80 &&
                   (static_cast<std::uint8_t>(utf8[i + 3]) & 0xC0) ==
                       0x80) {
            cp = ((byte & 0x07) << 18) |
                 ((static_cast<std::uint8_t>(utf8[i + 1]) & 0x3F) << 12) |
                 ((static_cast<std::uint8_t>(utf8[i + 2]) & 0x3F) << 6) |
                 (static_cast<std::uint8_t>(utf8[i + 3]) & 0x3F);
            len = 4;
        } else {
            cp = 0xFFFD;   // malformed byte -> '?' glyph, advance one
            len = 1;
        }
        lines.back().push_back(cp);
        i += len;
    }
    return lines;
}

// Straight-alpha src-over on one BGRA pixel — mirrors the compositor's
// AlphaOverPixel so layered font passes composite the same way.
void OverPixel(std::uint8_t* dst, const std::uint8_t* src) {
    const int sa = src[3];
    if (sa == 0) {
        return;
    }
    if (sa == 255) {
        dst[0] = src[0];
        dst[1] = src[1];
        dst[2] = src[2];
        dst[3] = 255;
        return;
    }
    const double s = sa / 255.0;
    const double d = dst[3] / 255.0;
    const double oa = s + d * (1.0 - s);
    if (oa <= 1e-9) {
        dst[0] = dst[1] = dst[2] = dst[3] = 0;
        return;
    }
    const double keep = d * (1.0 - s);
    for (int c = 0; c < 3; ++c) {
        dst[c] = static_cast<std::uint8_t>(std::clamp(
            (src[c] * s + dst[c] * keep) / oa + 0.5, 0.0, 255.0));
    }
    dst[3] = static_cast<std::uint8_t>(
        std::clamp(oa * 255.0 + 0.5, 0.0, 255.0));
}

