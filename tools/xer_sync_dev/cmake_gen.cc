std::string UpperIdent(const std::string& name) {
    std::string u;
    u.reserve(name.size());
    for (char c : name) {
        u += (std::isalnum(static_cast<unsigned char>(c)) ||
              c == '_')
                 ? static_cast<char>(std::toupper(
                       static_cast<unsigned char>(c)))
                 : '_';
    }
    return u;
}

std::string Q(const std::string& rel) {
    return "\"${CMAKE_CURRENT_LIST_DIR}/" + rel + "\"";
}

void EmitHeader(std::ostringstream& o, const Dependency& dep,
                const DepAnalysis& a, const GenContext& ctx) {
    o << "# xer-" << dep.name << ".cmake — generated by xer_sync_dev\n"
      << "# Do not edit: regenerated by `xer_sync_dev cmake-gen`.\n"
      << "# Upstream : " << ctx.upstream_url << "\n"
      << "# Revision : " << ctx.upstream_rev << "\n"
      << "# Applied  : " << ctx.applied_version
      << "   (prefix \"" << ctx.manifest->prefix_new_version_all_dependencies
      << "\" + upstream version)\n"
      << "# Generated: " << ctx.generated_at << "   analysis: "
      << (a.libclang_used ? "libclang include-graph + fs scan"
                          : "fs scan (libclang unavailable)")
      << "\n"
      << "# BuildMode: " << EffectiveBuildMode(*ctx.manifest, dep)
      << " (manifest default \"" << ctx.manifest->build_mode << "\")\n";
    if (!a.inter_dep_includes.empty()) {
        o << "# Inter-dep includes detected:";
        for (const auto& [d, n] : a.inter_dep_includes) {
            o << " " << d << "x" << n;
        }
        o << "\n";
    }
    if (!a.config_macros.empty()) {
        o << "# Config macros seen in guards (informational):\n#   ";
        int i = 0;
        for (const auto& [m, n] : a.config_macros) {
            if (++i > 30) {
                o << " ...";
                break;
            }
            o << m << " ";
        }
        o << "\n";
    }
    if (!a.platform_macros.empty()) {
        o << "# Platform guards referenced:";
        int i = 0;
        for (const auto& [m, n] : a.platform_macros) {
            if (++i > 12) {
                o << " ...";
                break;
            }
            o << " " << m;
        }
        o << "\n";
    }
    if (!a.warning.empty()) o << "# WARNING: " << a.warning << "\n";
    o << "\nset(XER_" << UpperIdent(dep.name) << "_ROOT "
      << "\"${CMAKE_CURRENT_LIST_DIR}\")\n"
      << "set(XER_" << UpperIdent(dep.name) << "_VERSION \""
      << ctx.applied_version << "\")\n\n";
}

void EmitGuardProlog(std::ostringstream& o, const std::string& name) {
    o << "if(TARGET XER-" << name << ")\n  return()\nendif()\n\n";
}

void EmitInterDepLinks(std::ostringstream& o, const DepAnalysis& a,
                       const std::string& vis) {
    for (const auto& [d, n] : a.inter_dep_includes) {
        o << "if(TARGET XER-" << d << ")\n"
          << "  target_link_libraries(XER-" << a.name << " " << vis
          << " XER-" << d << ")\n"
          << "endif()\n";
    }
}

// *_STATIC_DEFINE-style macros flip dllimport off for static builds —
// safe to emit. Everything else stays a comment (see header block).
std::vector<std::string> SafeDefines(const DepAnalysis& a) {
    std::vector<std::string> out;
    for (const auto& [m, n] : a.config_macros) {
        if (EndsWith(m, "_STATIC_DEFINE") || EndsWith(m, "_STATIC") ||
            EndsWith(m, "STATICLIB")) {
            out.push_back(m);
        }
    }
    return out;
}

