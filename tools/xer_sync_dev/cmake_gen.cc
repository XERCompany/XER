std::string GeneratePatch(const Dependency& dep,
                          const DepAnalysis& a,
                          const GenContext& ctx) {
    std::ostringstream o;
    EmitHeader(o, dep, a, ctx);
    EmitGuardProlog(o, dep.name);

    const bool needs_configure =
        (a.has_autotools || a.has_meson) && !a.has_upstream_cmake;

    if (needs_configure) {
        o << "set(XER_" << UpperIdent(dep.name)
          << "_REQUIRES_CONFIGURE TRUE)\n"
          << "message(WARNING \"xer-" << dep.name
          << ": upstream is autotools/meson-only — headers like "
             "config.h must be generated before this target can "
             "compile. Run upstream configure first.\")\n\n";
    }

    // --- binary tarball dep: imported shim --------------------------
    if (dep.kind == DepKind::kBinary) {
        // Look for conventional lib/include dirs to wire up hints.
        std::error_code ec;
        fs::path root = a.root;
        auto has_artifacts = [](const fs::path& d) {
            std::error_code ec2;
            for (const char* c : {"include", "lib", "lib64", "Release",
                                  "Debug", "bin"}) {
                if (fs::is_directory(d / c, ec2)) return true;
            }
            return false;
        };
        if (fs::is_directory(root, ec) && !has_artifacts(root)) {
            // Tarball payload usually sits one level down
            // (cef/cef_windows64, <pkg>/<pkg>-<ver>) — pick the first
            // child dir that actually carries the artifacts.
            for (const auto& e : fs::directory_iterator(root, ec)) {
                if (e.is_directory(ec) && has_artifacts(e.path())) {
                    root = e.path();
                    break;
                }
            }
        }
        std::vector<std::string> incs, libs, dlls;
        for (const char* cand : {"include", "lib", "lib64", "Release",
                                 "Debug", "bin"}) {
            const fs::path c = root / cand;
            if (!fs::is_directory(c, ec)) continue;
            if (std::string(cand) == "include") {
                incs.push_back(
                    GenericPath(fs::relative(c, a.root)));
            } else {
                for (const auto& e : fs::directory_iterator(c, ec)) {
                    const std::string x =
                        ToLower(e.path().extension().string());
                    if (x == ".lib" || x == ".a" || x == ".dll.a" ||
                        x == ".so") {
                        libs.push_back(
                            GenericPath(fs::relative(e.path(), a.root)));
                    } else if (x == ".dll") {
                        dlls.push_back(
                            GenericPath(fs::relative(e.path(), a.root)));
                    }
                }
            }
        }
        const std::string root_rel =
            root == a.root ? "" : GenericPath(fs::relative(root, a.root));
        o << "# Binary distribution shim — artifacts recorded for "
             "consumers.\n";
        if (!root_rel.empty()) {
            o << "set(XER_" << UpperIdent(dep.name) << "_PAYLOAD_DIR"
              << " \"${CMAKE_CURRENT_LIST_DIR}/" << root_rel << "\")\n";
        }
        // LIB_DIR = directory the discovered libs actually live in
        // (Release/ for CEF, lib/ for conventional layouts).
        if (!libs.empty()) {
            const std::string lib_dir =
                fs::path(libs.front()).parent_path().generic_string();
            o << "set(XER_" << UpperIdent(dep.name) << "_LIB_DIR"
              << " \"${CMAKE_CURRENT_LIST_DIR}/" << lib_dir << "\")\n";
        }
        if (!incs.empty()) {
            o << "add_library(XER-" << dep.name << " INTERFACE)\n"
              << "target_include_directories(XER-" << dep.name
              << " INTERFACE\n";
            for (const auto& i : incs) o << "  " << Q(i) << "\n";
            o << ")\n";
        }
        if (!libs.empty()) {
            o << "set(XER_" << UpperIdent(dep.name) << "_LIBRARIES\n";
            for (const auto& l : libs) {
                o << "  \"${CMAKE_CURRENT_LIST_DIR}/" << l << "\"\n";
            }
            o << ")\n";
        } else {
            o << "# No prebuilt libs found under include/lib/bin yet —\n"
              << "# set XER_" << UpperIdent(dep.name)
              << "_LIBRARIES manually.\n";
        }
        if (!dlls.empty()) {
            o << "# Runtime DLLs to stage beside executables.\n"
              << "set(XER_" << UpperIdent(dep.name) << "_RUNTIME_DLLS\n";
            for (const auto& l : dlls) {
                o << "  \"${CMAKE_CURRENT_LIST_DIR}/" << l << "\"\n";
            }
            o << ")\n";
        }
        return o.str();
    }

    // --- upstream CMake: thin wrapper --------------------------------
    if (a.has_upstream_cmake) {
        o << "# Upstream CMakeLists.txt detected (library targets: ";
        if (a.upstream_lib_targets.empty()) {
            o << "none detected";
        } else {
            for (size_t i = 0; i < a.upstream_lib_targets.size(); ++i) {
                o << (i ? ", " : "") << a.upstream_lib_targets[i];
            }
        }
        o << ").\n"
          << "# Scoped overrides the wrapper applies around upstream:\n"
          << "set(_xer_saved_BUILD_TESTING \"${BUILD_TESTING}\")\n"
          << "set(BUILD_TESTING OFF CACHE BOOL \"off via xer-" << dep.name
          << " wrapper\" FORCE)\n";
        const std::string bmode = EffectiveBuildMode(*ctx.manifest, dep);
        const bool force_shared =
            (bmode == "static" || bmode == "shared");
        if (force_shared) {
            // build_mode: force BUILD_SHARED_LIBS around the upstream
            // project, scoped save + restore like BUILD_TESTING.
            o << "set(_xer_saved_BUILD_SHARED_LIBS "
                 "\"${BUILD_SHARED_LIBS}\")\n"
              << "set(BUILD_SHARED_LIBS "
              << (bmode == "shared" ? "ON" : "OFF")
              << " CACHE BOOL \"forced via xer-" << dep.name
              << " wrapper (build_mode=" << bmode << ")\" FORCE)\n";
        }
        o << "add_subdirectory(\"${CMAKE_CURRENT_LIST_DIR}\"\n"
          << "               \"${CMAKE_BINARY_DIR}/xer_deps/" << dep.name
          << "\"\n"
          << "               EXCLUDE_FROM_ALL)\n"
          << "set(BUILD_TESTING \"${_xer_saved_BUILD_TESTING}\")\n";
        if (force_shared) {
            o << "set(BUILD_SHARED_LIBS "
                 "\"${_xer_saved_BUILD_SHARED_LIBS}\")\n";
        }
        o << "\n";

        if (!a.upstream_lib_targets.empty()) {
            o << "# Alias the upstream library under the XER- name.\n";
            for (size_t i = 0; i < a.upstream_lib_targets.size(); ++i) {
                o << (i == 0 ? "if" : "elseif") << "(TARGET "
                  << a.upstream_lib_targets[i] << ")\n"
                  << "  add_library(XER-" << dep.name << " ALIAS "
                  << a.upstream_lib_targets[i] << ")\n";
            }
            o << "else()\n"
              << "  message(STATUS \"xer-" << dep.name
              << ": no upstream lib target matched; link upstream "
                 "names directly\")\n"
              << "endif()\n";
        }
        return o.str();
    }

    // --- header-only --------------------------------------------------
    if (a.header_only) {
        o << "# Header-only dep -> INTERFACE target.\n"
          << "add_library(XER-" << dep.name << " INTERFACE)\n"
          << "target_include_directories(XER-" << dep.name
          << " INTERFACE\n";
        for (const auto& d : a.include_dirs) {
            o << "  " << Q(d) << "\n";
        }
        o << ")\n";
        const auto defs = SafeDefines(a);
        if (!defs.empty()) {
            o << "target_compile_definitions(XER-" << dep.name
              << " INTERFACE\n";
            for (const auto& m : defs) o << "  " << m << "\n";
            o << ")\n";
        }
        EmitInterDepLinks(o, a, "INTERFACE");
        return o.str();
    }

    // --- compiled sources, no upstream build files --------------------
    // STATIC is the manifest default; build_mode=shared flips the
    // keyword (BUILD_SHARED_LIBS is meaningless without an upstream
    // project to read it).
    const std::string slmode = EffectiveBuildMode(*ctx.manifest, dep);
    o << "# No upstream CMakeLists — sources enumerated by "
         "xer_sync_dev\n"
      << "# (" << a.sources.size() << " kept, "
      << a.excluded_sources.size()
      << " excluded by platform/test filter).\n"
      << "add_library(XER-" << dep.name << " "
      << (slmode == "shared" ? "SHARED" : "STATIC") << "\n";
    for (const auto& s : a.sources) o << "  " << Q(s) << "\n";
    o << ")\n"
      << "target_include_directories(XER-" << dep.name << "\n"
      << "  PUBLIC\n";
    for (const auto& d : a.include_dirs) o << "    " << Q(d) << "\n";
    o << "  PRIVATE\n    ${CMAKE_CURRENT_LIST_DIR}\n";
    {
        // src/ is a common private-include convention but not universal
        // (lz4 keeps sources under lib/) — emit only when it exists, or
        // VerifyPatch flags a missing referenced path.
        std::error_code sec;
        if (fs::is_directory(a.root / "src", sec)) {
            o << "    ${CMAKE_CURRENT_LIST_DIR}/src\n";
        }
    }
    o << ")\n";

    const auto defs = SafeDefines(a);
    if (!defs.empty()) {
        o << "target_compile_definitions(XER-" << dep.name
          << " PUBLIC\n";
        for (const auto& m : defs) o << "  " << m << "\n";
        o << ")\n";
    }
    EmitInterDepLinks(o, a, "PUBLIC");

    if (!a.config_templates.empty()) {
        o << "\n# Generated-header templates found — configure step "
             "may be required:\n";
        int i = 0;
        for (const auto& t : a.config_templates) {
            if (++i > 15) {
                o << "#   ... (" << a.config_templates.size() - 15
                  << " more)\n";
                break;
            }
            o << "#   " << t << "\n";
        }
    }
    if (!a.excluded_sources.empty()) {
        o << "\n# Excluded sources (platform/test filter) — review if "
             "build breaks:\n";
        int i = 0;
        for (const auto& s : a.excluded_sources) {
            if (++i > 15) {
                o << "#   ... (" << a.excluded_sources.size() - 15
                  << " more)\n";
                break;
            }
            o << "#   " << s << "\n";
        }
    }
    return o.str();
}

bool WritePatch(const fs::path& dep_root, const std::string& name,
                const std::string& content, fs::path* written,
                std::string* error) {
    const fs::path out = dep_root / ("xer-" + name + ".cmake");
    std::ofstream f(out, std::ios::binary | std::ios::trunc);
    if (!f.is_open()) {
        if (error) *error = "cannot write " + out.string();
        return false;
    }
    f << content;
    if (!f.good()) {
        if (error) *error = "write failed for " + out.string();
        return false;
    }
    if (written) *written = out;
    return true;
}

bool VerifyPatch(const fs::path& patch_file,
                 std::vector<std::string>* problems) {
    problems->clear();
    std::ifstream in(patch_file);
    if (!in.is_open()) {
        problems->push_back("cannot open " + patch_file.string());
        return false;
    }

    static const std::set<std::string> kCommands = {
        "add_library", "add_executable", "add_subdirectory",
        "target_include_directories", "target_compile_definitions",
        "target_compile_options", "target_link_libraries",
        "target_link_directories", "target_link_options",
        "target_sources", "target_compile_features",
        "target_precompile_headers", "add_dependencies",
        "set", "unset", "option", "if", "elseif", "else", "endif",
        "foreach", "endforeach", "while", "endwhile", "function",
        "endfunction", "macro", "endmacro", "include", "include_guard",
        "return", "message", "list", "string", "math", "file",
        "find_package", "find_library", "find_path", "find_file",
        "find_program", "configure_file", "add_custom_command",
        "add_custom_target", "get_filename_component",
        "get_target_property", "set_target_properties",
        "get_property", "set_property", "project",
        "cmake_minimum_required", "cmake_policy", "install",
        "mark_as_advanced", "block", "endblock", "break", "continue",
        "add_compile_options", "add_compile_definitions",
        "add_link_options", "link_directories", "link_libraries",
        "include_directories", "add_definitions", "enable_language",
        "set_property", "define_property", "try_compile",
        "check_include_file", "check_cxx_source_compiles",
        "cmake_parse_arguments", "separate_arguments",
        "execute_process", "add_test", "source_group",
        "target_sources", "target_include_directories",
        "set_target_properties", "get_cmake_property", "export",
        "include_directories", "aux_source_directory",
    };

    const fs::path base = patch_file.parent_path();
    int depth = 0;
    std::string line;
    int lineno = 0;
    bool in_string = false;  // crude: quotes per line

    static const std::regex cmd_re(
        R"(^\s*([A-Za-z_][A-Za-z0-9_]*)\s*\()");
    static const std::regex path_re(
        R"(\$\{CMAKE_CURRENT_LIST_DIR\}/([^"\s)]+))");

    while (std::getline(in, line)) {
        ++lineno;
        // strip comments (naive — '#' inside a string is rare in our output)
        const size_t hash = line.find('#');
        if (hash != std::string::npos) line = line.substr(0, hash);
        for (char c : line) {
            if (c == '"') in_string = !in_string;
            if (in_string) continue;
            if (c == '(') ++depth;
            if (c == ')') --depth;
            if (depth < 0) {
                problems->push_back("line " + std::to_string(lineno) +
                                    ": unmatched ')'");
                depth = 0;
            }
        }
        std::smatch m;
        if (std::regex_search(line, m, cmd_re)) {
            const std::string cmd = m[1].str();
            if (!kCommands.count(cmd)) {
                problems->push_back("line " + std::to_string(lineno) +
                                    ": unknown command '" + cmd + "'");
            }
        }
        for (std::sregex_iterator it(line.begin(), line.end(), path_re),
             end;
             it != end; ++it) {
            const fs::path p = base / (*it)[1].str();
            std::error_code ec;
            if (!fs::exists(p, ec)) {
                problems->push_back("line " + std::to_string(lineno) +
                                    ": referenced path missing: " +
                                    (*it)[1].str());
            }
        }
        // add_subdirectory("<dir>" ...) must point at a dir with
        // CMakeLists.txt — check ${CMAKE_CURRENT_LIST_DIR} literals.
        if (line.find("add_subdirectory") != std::string::npos) {
            std::smatch dm;
            static const std::regex dir_re(
                R"(add_subdirectory\s*\(\s*"\$\{CMAKE_CURRENT_LIST_DIR\}([^"]*))");
            if (std::regex_search(line, dm, dir_re)) {
                std::string rel = dm[1].str();
                while (StartsWith(rel, "/")) rel = rel.substr(1);
                const fs::path d = base / rel;
                std::error_code ec;
                if (!fs::exists(d / "CMakeLists.txt", ec)) {
                    problems->push_back(
                        "line " + std::to_string(lineno) +
                        ": add_subdirectory target lacks CMakeLists.txt");
                }
            }
        }
    }
    if (depth != 0) {
        problems->push_back("unbalanced parentheses (depth " +
                            std::to_string(depth) + " at EOF)");
    }
    return problems->empty();
}

